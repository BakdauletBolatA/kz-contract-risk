"""Маскирование персональных данных перед отправкой пункта во внешний API.

⚠ Юридический риск. Отправка текста договора в API за пределами РК —
трансграничная передача персональных данных (ст. 16 Закона РК «О
персональных данных и их защите»). Поэтому:

- реквизиты в LLM не уходят вообще (сегментатор помечает их `requisites`);
- в пунктах маскируются ИИН/БИН, IBAN, телефоны и e-mail;
- ФИО не маскируются: надёжно отличить фамилию от слова в договоре
  регулярным выражением нельзя. Это ограничение описано в README; для
  промышленного использования нужен NER или согласие субъекта.

Маскирование не меняет смысла пункта для классификации риска: ставки,
сроки и роли сторон остаются.
"""

from __future__ import annotations

import re

_PATTERNS: list[tuple[re.Pattern, str]] = [
    # IBAN РК — 20 символов: KZ, 2 контрольные цифры, 16 знаков; бывает группами по 4.
    (re.compile(r"\bKZ\d{2}(?:\s?[A-Z0-9]{4}){4}\b"), "[IBAN]"),
    (re.compile(r"(?<!\d)\d{12}(?!\d)"), "[ИИН/БИН]"),
    (re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+"), "[EMAIL]"),
    (
        re.compile(r"(?<!\d)(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}(?!\d)"),
        "[ТЕЛЕФОН]",
    ),
]


def redact(text: str) -> tuple[str, int]:
    """Текст с масками и число замен."""
    total = 0
    for pattern, mask in _PATTERNS:
        text, n = pattern.subn(mask, text)
        total += n
    return text, total
